"""
Score prepared negative-sampled queries using a trained VL-KGE model.

Loads a checkpointed model, reads query CSVs generated by prepare.py,
scores all (positive + negative) triples, and writes score CSVs in the
format expected by evaluate.py:

    query_id,score,is_positive
    0,3.14,1
    0,-0.50,0

Usage:
    python -m pmr.models.vlkge.score --config configs/eval/wikiart_mkg_v2_score.yaml
"""

import argparse
import json
import os
import sys
from collections import defaultdict
from pathlib import Path
from types import SimpleNamespace

import time

import numpy as np
import pandas as pd
import torch
import torch.nn as nn
from tqdm import tqdm

from pmr.dataloader import KnowledgeGraphDataLoader
from pmr import helpers, utils

SCRIPT_DIR = Path(__file__).parent.resolve()    # pmr/models/vlkge/
PKG_ROOT   = SCRIPT_DIR.parent.parent          # mmkg-pmr/pmr/
REPO_ROOT  = PKG_ROOT.parent                   # mmkg-pmr/
WS_ROOT    = REPO_ROOT.parent                  # pmr/ (workspace)


def parse_args():
    parser = argparse.ArgumentParser(
        description="Score prepared queries using a trained model"
    )
    parser.add_argument("--config", type=str, required=True,
                        help="Path to score YAML config file")
    parser.add_argument("--no-cuda", action="store_true",
                        help="Disable CUDA")
    return parser.parse_args()


def _resolve_single_config(path_str, base_dir):
    """Resolve a YAML config path, returning (config_dict, base_dir_of_config)."""
    pp = Path(path_str).expanduser()
    if not pp.is_absolute():
        for candidate in [base_dir / pp, PKG_ROOT / pp, REPO_ROOT / pp, Path.cwd() / pp]:
            if candidate.exists():
                pp = candidate.resolve()
                break
    if not pp.exists():
        raise FileNotFoundError(f"Config not found: {path_str}")
    cfg = utils.load_yaml_config(pp)
    cfg = utils.resolve_config_paths(cfg, base_dir=pp.parent, repo_root=REPO_ROOT)
    return cfg


def main():
    args_cli = parse_args()

    # ── 1. Load score config ─────────────────────────────────────────────
    score_path = Path(args_cli.config).expanduser()
    if not score_path.is_absolute():
        for candidate in [Path.cwd() / score_path, REPO_ROOT / score_path]:
            if candidate.exists():
                score_path = candidate.resolve()
                break
    if not score_path.exists():
        raise FileNotFoundError(f"Score config not found: {args_cli.config}")

    scfg = utils.load_yaml_config(score_path)
    scfg = utils.resolve_config_paths(scfg, base_dir=score_path.parent, repo_root=REPO_ROOT)

    # ── 2. Load configs: self-contained or reference mode ────────────────
    self_contained = "prepare_config" not in scfg

    if self_contained:
        # Self-contained: all keys in score config directly
        output_dir = scfg["output_dir"]
        if not Path(output_dir).is_absolute():
            output_dir = str((REPO_ROOT / output_dir).resolve())
        queries_dir = output_dir
        model_cfg = scfg  # read model params directly from score config
    else:
        # Reference mode: load prepare + model configs separately
        prepare_cfg = _resolve_single_config(scfg["prepare_config"], score_path.parent)
        model_cfg = _resolve_single_config(scfg["model_config"], score_path.parent)
        # Queries from prepare output_dir; scores to scfg output_dir (if set)
        queries_dir = prepare_cfg["output_dir"]
        if not Path(queries_dir).is_absolute():
            queries_dir = str((REPO_ROOT / queries_dir).resolve())
        output_dir = scfg.get("output_dir") or queries_dir
        if not Path(output_dir).is_absolute():
            output_dir = str((REPO_ROOT / output_dir).resolve())

    checkpoint_path = scfg["checkpoint_path"]
    if not Path(checkpoint_path).is_absolute():
        checkpoint_path = str(WS_ROOT / checkpoint_path)
    if not os.path.exists(checkpoint_path):
        raise FileNotFoundError(f"Checkpoint not found: {checkpoint_path}")

    batch_size = scfg.get("batch_size", 2048)
    seed = scfg.get("seed", 42)
    log_metrics = scfg.get("log_metrics", False)

    # ── Optional relation filter ─────────────────────────────────────────
    rel_filter = scfg.get("relation_filter") or {}
    rel_mode = rel_filter.get("mode", "none")
    rel_list = set(rel_filter.get("relations", [])) if rel_mode != "none" else None

    utils.set_seed(seed)
    device = torch.device("cuda" if torch.cuda.is_available() and not args_cli.no_cuda else "cpu")

    print("=" * 80)
    print("NEGATIVE-SAMPLED EVALUATION — SCORE")
    print("=" * 80)
    if self_contained:
        print(f"Mode:             self-contained")
    else:
        print(f"Prepare config:   {scfg['prepare_config']}")
        print(f"Model config:     {scfg['model_config']}")
    print(f"Checkpoint:       {checkpoint_path}")
    print(f"Output dir:       {output_dir}")
    print(f"Device:           {device}")
    print(f"Batch size:       {batch_size}")
    print(f"Log metrics:      {log_metrics}")
    print("=" * 80)

    # ── 5. Load KnowledgeGraphDataLoader ──────────────────────────────────
    print("\nLoading dataset...")
    dl = KnowledgeGraphDataLoader(
        data_path=model_cfg["data_path"],
        dataset_name=model_cfg["dataset"],
        exclude_relations=model_cfg.get("exclude_relations"),
        exclude_relations_eval=model_cfg.get("exclude_relations_eval"),
        inverse_relation_pairs=model_cfg.get("inverse_relation_pairs"),
        symmetric_relations=model_cfg.get("symmetric_relations"),
        use_per_relation_candidates=model_cfg.get("use_per_relation_candidates", True),
        artist2artist_relations=model_cfg.get("artist2artist_relations"),
        bidirectional_eval=model_cfg.get("bidirectional_eval", False),
    )

    entity_to_id, relation_to_id = dl.get_entities_and_relations()
    print(f"  Entities:  {len(entity_to_id):,}")
    print(f"  Relations: {dl.get_num_relations():,}")

    # ── 6. Load features ──────────────────────────────────────────────────
    print("\nLoading features...")
    feat_args = SimpleNamespace(
        use_visual=model_cfg.get("use_visual", True),
        use_textual=model_cfg.get("use_textual", True),
        use_relation_features=model_cfg.get("use_relation_features", False),
        visual_features_path=model_cfg.get("visual_features_path"),
        textual_features_path=model_cfg.get("textual_features_path"),
        relation_features_path=model_cfg.get("relation_features_path"),
        normalize_visual=model_cfg.get("normalize_visual", False),
        normalize_textual=model_cfg.get("normalize_textual", False),
        normalize_relation=model_cfg.get("normalize_relation", False),
    )

    (visual_features, textual_features, relation_features,
     visual_entity_to_index, textual_entity_to_index) = utils.load_features(
         feat_args, entity_to_id, relation_to_id,
         num_relations=dl.get_num_relations())

    # ── 7. Build model ────────────────────────────────────────────────────
    print("\nBuilding model...")

    # The relation mapping is part of the checkpoint contract. Do not create
    # zero-padded relation rows for a mismatched mapping.
    relation_registry = dl.get_relation_registry()
    print(f"\nLoading checkpoint: {checkpoint_path}")
    if not os.path.exists(checkpoint_path):
        raise FileNotFoundError(f"Checkpoint not found: {checkpoint_path}")
    ckpt = torch.load(checkpoint_path, map_location="cpu")
    state = ckpt.get("model_state_dict", ckpt)
    n_ckpt_rels = state["relation_embeddings.weight"].shape[0]
    n_ckpt_ents = state["entity_embeddings.weight"].shape[0]
    n_data_rels = dl.get_num_relations()
    n_data_ents = len(entity_to_id)
    if n_ckpt_rels != n_data_rels:
        raise ValueError(
            "VLKGE checkpoint relation count does not match the current "
            f"DataLoader registry ({n_ckpt_rels} vs {n_data_rels}). "
            "Retrain the checkpoint with the canonical registry."
        )
    ckpt_registry = ckpt.get("relation_registry") or {}
    if ckpt_registry.get("registry_hash") != relation_registry.registry_hash:
        raise ValueError(
            "VLKGE checkpoint lacks an identical relation-registry hash. "
            "Equal relation counts do not prove ID alignment. Retrain the "
            "checkpoint with the current canonical registry."
        )
    model_rel_count = n_data_rels

    # Save references to padded keys before deleting them from state
    ckpt_ent_w = state.get("entity_embeddings.weight")
    ckpt_ent_im_w = state.get("entity_embeddings_imag.weight")
    ckpt_txt_w = state.get("textual_embeddings.weight")
    ckpt_seen = state.get("seen_in_train")

    model, _, _ = helpers.get_model(
        model_name=model_cfg["model"],
        num_entities=n_data_ents,
        num_relations=model_rel_count,
        visual_features=visual_features,
        textual_features=textual_features,
        relation_features=relation_features,
        visual_entity_to_index=visual_entity_to_index,
        textual_entity_to_index=textual_entity_to_index,
        embedding_dim=model_cfg.get("embedding_dim", 768),
        fusion_mode=model_cfg.get("fusion_mode", "average"),
        use_structural=model_cfg.get("use_structural", True),
        use_visual=model_cfg.get("use_visual", True),
        use_textual=model_cfg.get("use_textual", True),
        freeze_visual=model_cfg.get("freeze_visual", True),
        freeze_textual=model_cfg.get("freeze_textual", True),
        visual_proj=model_cfg.get("visual_proj", False),
        textual_proj=model_cfg.get("textual_proj", False),
        shared_projection=model_cfg.get("shared_projection"),
        inductive=model_cfg.get("inductive", False),
        modality_asymmetry=model_cfg.get("modality_asymmetry", False),
        normalize_before_fusion=model_cfg.get("normalize_before_fusion", False),
        p_norm=model_cfg.get("p_norm", 1),
        normalize_relations=model_cfg.get("normalize_relations", True),
        margin=model_cfg.get("margin", 12.0),
        lr=model_cfg.get("lr", 0.1),
        use_scheduler=False,
        device=device,
    )

    # ── 8. Load checkpoint ────────────────────────────────────────────────
    # Defer size-mismatched keys (artist-only training has fewer entities)
    # Full-mode checkpoints have matching sizes — no deferral needed.
    mismatch_keys = []
    for k in ["entity_embeddings.weight", "entity_embeddings_imag.weight",
              "textual_embeddings.weight", "seen_in_train"]:
        if k in state and k in model.state_dict():
            if state[k].shape != model.state_dict()[k].shape:
                mismatch_keys.append(k)
    skip_keys = set()
    for k in mismatch_keys:
        del state[k]
        skip_keys.add(k)
    if skip_keys:
        print(f"  Deferred {len(skip_keys)} mismatched keys for zero-padding: {sorted(skip_keys)}")

    missing_keys, unexpected_keys = model.load_state_dict(state, strict=False)
    if missing_keys:
        print(f"  Note: {len(missing_keys)} missing, {len(unexpected_keys)} unexpected")

    # Pad entity embeddings if checkpoint has fewer entities than DataLoader
    n_model_ents = model.entity_embeddings.weight.shape[0]
    if n_data_ents > n_ckpt_ents and ckpt_ent_w is not None:
        missing = n_data_ents - n_ckpt_ents
        missing = n_data_ents - n_ckpt_ents
        d_ent = model.entity_embeddings.weight.shape[1]
        dev = model.entity_embeddings.weight.device
        ckpt_ent = ckpt_ent_w.to(dev)
        ext = torch.zeros(missing, d_ent, device=dev)
        model.entity_embeddings.weight = nn.Parameter(
            torch.cat([ckpt_ent, ext]))
        if ckpt_ent_im_w is not None and hasattr(model, 'entity_embeddings_imag'):
            ckpt_ent_im = ckpt_ent_im_w.to(dev)
            ext_im = torch.zeros(missing, d_ent, device=dev)
            model.entity_embeddings_imag.weight = nn.Parameter(
                torch.cat([ckpt_ent_im, ext_im]))
        if ckpt_seen is not None and hasattr(model, 'seen_in_train'):
            ckpt_seen_t = ckpt_seen.to(dev)
            model.seen_in_train = torch.cat([
                ckpt_seen_t,
                torch.zeros(missing, dtype=ckpt_seen_t.dtype, device=dev)
            ])
        print(f"  Padded entity embeddings: {n_ckpt_ents:,} → {n_data_ents:,}"
              f" ({missing:,} zeros)")

    # Pad textual_embeddings too (artist-only training has fewer textual entities)
    if hasattr(model, 'textual_embeddings') and ckpt_txt_w is not None:
        n_model_txt = model.textual_embeddings.weight.shape[0]
        ckpt_txt = ckpt_txt_w.to(model.textual_embeddings.weight.device)
        n_ckpt_txt = ckpt_txt.shape[0]
        if n_model_txt > n_ckpt_txt:
            missing = n_model_txt - n_ckpt_txt
            ext = torch.zeros(missing, ckpt_txt.shape[1], device=ckpt_txt.device)
            model.textual_embeddings.weight = nn.Parameter(
                torch.cat([ckpt_txt, ext]))
            print(f"  Padded textual_embeddings: {n_ckpt_txt:,} → {n_model_txt:,}")

    model.eval()
    print(f"  Loaded (epoch {ckpt.get('epoch', '?')}, val MRR {ckpt.get('score', ckpt.get('best_val_mrr', '?'))})")

    # ── 9. Mark seen entities for inductive evaluation ────────────────────
    if model_cfg.get("inductive", False) and hasattr(model, "mark_seen_entities"):
        train_data, _, _ = dl.split_data()
        seen = set(train_data["head"]).union(set(train_data["tail"]))
        train_ids = torch.tensor(
            [entity_to_id[e] for e in seen if e in entity_to_id],
            dtype=torch.long,
        )
        model.mark_seen_entities(train_ids)
        print(f"  Marked {len(train_ids):,} seen entities (inductive)")

    print(f"\n  Parameters: {sum(p.numel() for p in model.parameters()):,}")

    # ── 10. Score queries per split ───────────────────────────────────────
    os.makedirs(output_dir, exist_ok=True)
    splits = []

    for split_name in ["train", "val", "test"]:
        queries_path = os.path.join(queries_dir, f"{split_name}_queries.csv")
        if not os.path.exists(queries_path):
            print(f"\n  SKIP {split_name}: queries CSV not found ({queries_path})")
            continue
        splits.append((split_name, queries_path))

    if not splits:
        print("\nERROR: No query CSVs found. Nothing to score.")
        sys.exit(1)

    for split_name, queries_path in splits:
        print(f"\n{'─' * 60}")
        print(f"  {split_name.upper()}")
        print(f"{'─' * 60}")

        df = pd.read_csv(queries_path)
        if rel_list:
            df = df[df["relation"].isin(rel_list)]
        n_rows = len(df)
        print(f"  Loaded {n_rows:,} rows from {queries_path}")

        head_ids = torch.tensor(df["head_id"].values, dtype=torch.long, device=device)
        rel_ids = torch.tensor(df["relation_id"].values, dtype=torch.long, device=device)
        tail_ids = torch.tensor(df["tail_id"].values, dtype=torch.long, device=device)
        query_ids = df["query_id"].values
        is_pos = df["is_positive"].values

        all_scores = np.empty(n_rows, dtype=np.float32)

        if log_metrics and device.type == "cuda":
            torch.cuda.reset_peak_memory_stats()
        wall_start = time.perf_counter() if log_metrics else None
        cpu_start = time.process_time() if log_metrics else None
        batch_times = [] if log_metrics else None

        n_batches = (n_rows + batch_size - 1) // batch_size
        with torch.no_grad():
            for b in tqdm(range(n_batches), desc=f"  Scoring {split_name}", unit="batch"):
                if log_metrics:
                    b_start = time.perf_counter()
                start = b * batch_size
                end = min(start + batch_size, n_rows)
                scores = model(head_ids[start:end], rel_ids[start:end], tail_ids[start:end])
                all_scores[start:end] = scores.cpu().numpy()
                if log_metrics:
                    batch_times.append(time.perf_counter() - b_start)

        # Write scores CSV
        scores_path = os.path.join(output_dir, f"{split_name}_scores.csv")
        scores_df = pd.DataFrame({
            "query_id": query_ids,
            "score": all_scores,
            "is_positive": is_pos,
        })
        scores_df.to_csv(scores_path, index=False)
        print(f"  → {scores_path}  ({n_rows:,} rows)")

        if log_metrics:
            wall_time = time.perf_counter() - wall_start
            cpu_time = time.process_time() - cpu_start
            gpu_alloc = (torch.cuda.max_memory_allocated() / (1024 ** 2)
                         if device.type == "cuda" else 0.0)
            gpu_reserved = (torch.cuda.max_memory_reserved() / (1024 ** 2)
                            if device.type == "cuda" else 0.0)
            avg_batch_ms = (sum(batch_times) / len(batch_times) * 1000
                            if batch_times else 0.0)
            max_batch_ms = (max(batch_times) * 1000 if batch_times else 0.0)

            metrics = {
                "split": split_name,
                "num_queries": int(scores_df["query_id"].nunique()),
                "num_rows": n_rows,
                "batch_size": batch_size,
                "num_batches": n_batches,
                "wall_time_seconds": round(wall_time, 3),
                "cpu_time_seconds": round(cpu_time, 3),
                "gpu_memory_allocated_mb": round(gpu_alloc, 2),
                "gpu_memory_reserved_mb": round(gpu_reserved, 2),
                "param_count": sum(p.numel() for p in model.parameters()),
                "avg_batch_time_ms": round(avg_batch_ms, 2),
                "max_batch_time_ms": round(max_batch_ms, 2),
            }
            metrics_path = os.path.join(output_dir, f"{split_name}_score_metrics.json")
            with open(metrics_path, "w") as f:
                json.dump(metrics, f, indent=2)
            print(f"        → {metrics_path}")
            print(f"           wall={wall_time:.1f}s  cpu={cpu_time:.1f}s  "
                  f"gpu_alloc={gpu_alloc:.0f}MB  avg_batch={avg_batch_ms:.0f}ms")

    print("\n" + "=" * 80)
    print("SCORING COMPLETE")
    print("=" * 80)


if __name__ == "__main__":
    main()
